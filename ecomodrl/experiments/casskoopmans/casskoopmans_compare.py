"""
Cass-Koopmans comparison analysis: generates comparison plots and LaTeX table.

This script loads pre-computed metrics from each algorithm's `metrics_analysis.json`
(generated by `analyze_all_seeds()`) and produces:
1. Learning curves (regret plot)
2. Policy function comparison (2x2 grid)
3. Euler error histograms (4x1 stack)
4. CEV analysis with state density (1x4)
5. LaTeX comparison table

Run after training all algorithms:
    python ecomodrl/experiments/casskoopmans/casskoopmans_compare.py
"""
import json
import logging
import os
from pathlib import Path

import matplotlib.pyplot as plt
import matplotlib.ticker as ticker
import numpy as np

from ecomodrl.benchmarks.casskoopmans.problemclass import PlanningProblem, PlanningSolvers
from ecomodrl.utils.metrics.performance import get_bootstrapped_iqm_ci
from ecomodrl.utils.params_loader import CassKoopmansParams
from ecomodrl.utils.latex_formatting import generate_latex_table

# ----------------------------------------------------------------------------
# Configuration
# ----------------------------------------------------------------------------
ALGOS = ["PPO", "DDPG", "SAC", "TD3"]
TOML_PATH = Path("ecomodrl/experiments/model_params/casskoopmans.toml")
RUNRESULTS_PATH = Path(os.environ.get("RUNRESULTS_PATH", "./runs/CassKoopmans"))

# Plotting style
plt.style.use("seaborn-v0_8-colorblind")
plt.rcParams.update({
    "text.usetex": False,
    "font.family": "serif",
    "mathtext.fontset": "cm",
    "font.serif": ["cmr10"],
    "axes.formatter.use_mathtext": True,
    "font.size": 12,
    "axes.labelsize": 12,
    "legend.fontsize": 10,
    "xtick.labelsize": 10,
    "ytick.labelsize": 10,
})

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(name)s: %(message)s")
logger = logging.getLogger("CKComparison")


# ----------------------------------------------------------------------------
# Data Loading
# ----------------------------------------------------------------------------

def load_algo_metrics(algo: str) -> dict | None:
    """Load metrics_analysis.json for a given algorithm."""
    json_path = RUNRESULTS_PATH / algo / "metrics_analysis.json"
    if not json_path.exists():
        logger.warning(f"Missing metrics for {algo}: {json_path}")
        return None
    with open(json_path, "r", encoding="utf-8") as f:
        return json.load(f)


def compute_benchmark(params):
    """Compute EGM benchmark solution."""
    model = PlanningProblem(
        gamma=params.gamma,
        beta=params.beta,
        delta=params.delta,
        alpha=params.alpha,
        A=params.A
    )
    solvers = PlanningSolvers(grid_points=1000, conv=1e-5)
    policy_bm = solvers.EGM(model)
    grid = model.make_grid(solvers.grid_points)
    V_bm = model.V_from_a(grid, policy_bm, conv=1e-5)
    return model, grid, policy_bm, V_bm


# ----------------------------------------------------------------------------
# Plotting Functions
# ----------------------------------------------------------------------------

def plot_learning_curves(results: dict, out_dir: Path):
    """Learning curves as regret (G_EGM - G_RL) with log scale."""
    _, ax = plt.subplots(figsize=(8, 5))

    for algo in ALGOS:
        if algo not in results or results[algo] is None:
            continue
        
        data = results[algo]
        curves = np.array(data.get("_return_curves", []))
        steps = np.array(data.get("_global_steps", []))
        benchmark_ret = data.get("return_bm", 0)
        
        if len(curves) == 0 or len(steps) == 0:
            continue

        # Compute regret: (benchmark - RL return)
        iqm, ci_lower, ci_upper = get_bootstrapped_iqm_ci(curves)
        regret_iqm = benchmark_ret - iqm
        regret_upper = benchmark_ret - ci_lower  # Flipped due to subtraction
        regret_lower = benchmark_ret - ci_upper

        line = ax.plot(steps, regret_iqm, label=algo)
        ax.fill_between(steps, regret_lower, regret_upper, color=line[0].get_color(), alpha=0.2)

    ax.set_yscale('log')
    ax.yaxis.set_major_formatter(ticker.FuncFormatter(lambda y, _: f'{y:g}'))
    ax.set_xlabel("Processed Samples")
    ax.set_ylabel(r"Regret $(G_{EGM} - G_{RL})$", fontsize=10)
    ax.grid(True, which="major", linestyle="--", alpha=0.5)
    ax.grid(True, which="minor", linestyle=":", alpha=0.2)
    ax.legend()
    
    plt.tight_layout()
    plt.savefig(out_dir / "1_learning_curves.pdf", format="pdf")
    plt.close()
    logger.info("Saved: 1_learning_curves.pdf")


def plot_policy_functions(results: dict, grid: np.ndarray, policy_bm, out_dir: Path):
    """2x2 grid of policy functions with unified legend."""
    fig, axes = plt.subplots(2, 2, figsize=(10, 8))
    axes = axes.flatten()

    # Determine global y-limits
    bm_vals = policy_bm(grid)
    y_min, y_max = bm_vals.min(), bm_vals.max()
    
    for algo in ALGOS:
        if algo in results and results[algo] is not None:
            policies = np.array(results[algo].get("_policies", []))
            if len(policies) > 0:
                y_min = min(y_min, policies.min())
                y_max = max(y_max, policies.max())

    handles, labels = [], []

    for i, algo in enumerate(ALGOS):
        ax = axes[i]
        
        if algo not in results or results[algo] is None:
            ax.set_title(f"{algo} (No Data)")
            ax.set_xlabel("Capital k")
            ax.set_ylabel("Consumption c")
            continue

        policies = np.array(results[algo].get("_policies", []))
        if len(policies) == 0:
            ax.set_title(f"{algo} (No Data)")
            ax.set_xlabel("Capital k")
            ax.set_ylabel("Consumption c")
            continue

        iqm, lo, hi = get_bootstrapped_iqm_ci(policies)
        
        ax.plot(grid, iqm, label="RL IQM")
        ax.fill_between(grid, lo, hi, alpha=0.3, label="95% CI")
        ax.plot(grid, bm_vals, "k--", label="EGM", alpha=0.6)
        
        if not handles:
            handles, labels = ax.get_legend_handles_labels()

        ax.set_title(algo)
        ax.set_xlabel("Capital k")
        ax.set_ylabel("Consumption c")

    # Unified y-limits
    pad = (y_max - y_min) * 0.05
    for ax in axes:
        ax.set_ylim(y_min - pad, y_max + pad)

    if handles:
        fig.legend(handles, labels, loc='lower center', ncol=3, bbox_to_anchor=(0.5, 0.02))

    plt.tight_layout(rect=[0, 0.06, 1, 1])
    plt.savefig(out_dir / "2_policy_functions.pdf", format="pdf")
    plt.close()
    logger.info("Saved: 2_policy_functions.pdf")


def plot_euler_errors(results: dict, out_dir: Path):
    """4x1 vertical stack of Euler error histograms."""
    _, axes = plt.subplots(len(ALGOS), 1, figsize=(8, 10))
    if len(ALGOS) == 1:
        axes = [axes]

    # Compute global x-limits across all algorithms
    all_errors = []
    for algo in ALGOS:
        if algo in results and results[algo] is not None:
            euler_list = results[algo].get("_euler_errors", [])
            for e in euler_list:
                all_errors.extend(e)
    
    if all_errors:
        all_errors = np.array(all_errors)
        x_min = np.percentile(all_errors, 0.1)
        x_max = all_errors.max()
    else:
        x_min, x_max = -5, 0

    for i, algo in enumerate(ALGOS):
        ax = axes[i]
        
        if algo in results and results[algo] is not None:
            euler_list = results[algo].get("_euler_errors", [])
            if euler_list:
                # Flatten all seeds' Euler errors
                euler_flat = np.concatenate([np.array(e) for e in euler_list])
                ax.hist(euler_flat, bins=50, density=True, alpha=0.8, edgecolor='white', linewidth=0.5)
                ax.set_ylabel("Density", fontsize=10)
                ax.set_title(algo, fontweight='bold')
            else:
                ax.text(0.5, 0.5, "No Data", ha='center', transform=ax.transAxes)
        else:
            ax.text(0.5, 0.5, "No Data", ha='center', transform=ax.transAxes)

        ax.set_xlim(x_min - 0.5, x_max + 0.5)

    axes[-1].set_xlabel(r"$\log_{10} | \text{Euler Error} |$", fontsize=11)

    plt.tight_layout()
    plt.savefig(out_dir / "3_euler_errors.pdf", format="pdf")
    plt.close()
    logger.info("Saved: 3_euler_errors.pdf")


def plot_cev(results: dict, grid: np.ndarray, out_dir: Path):
    """1x4 CEV plots with state density histogram overlay."""
    # Pre-compute stats for global y-limits
    plot_data = {}
    y_min, y_max = np.inf, -np.inf
    
    for algo in ALGOS:
        if algo in results and results[algo] is not None:
            cev_vals = np.array(results[algo].get("_cev", []))
            if len(cev_vals) > 0:
                iqm, lo, hi = get_bootstrapped_iqm_ci(cev_vals)
                y_min = min(y_min, lo.min())
                y_max = max(y_max, hi.max())
                plot_data[algo] = (iqm, lo, hi)

    if y_min == np.inf:
        y_min, y_max = 0.001, 0.1
    else:
        y_max = y_max * 1.1

    fig, axes = plt.subplots(1, 4, figsize=(16, 4), sharex=True, sharey=True)
    handles, labels = [], []

    for i, algo in enumerate(ALGOS):
        ax = axes[i]

        if algo not in plot_data:
            ax.set_title(f"{algo} (No Data)")
            ax.set_xlabel("Capital k")
            continue

        iqm, lo, hi = plot_data[algo]

        ax.plot(grid, iqm, label="CEV", linewidth=2, zorder=3)
        ax.fill_between(grid, lo, hi, alpha=0.3, label="95% CI", zorder=2)

        ax.set_title(algo)
        ax.set_xlabel("Capital k")
        ax.set_yscale("log")
        ax.yaxis.set_major_formatter(ticker.FuncFormatter(lambda y, _: f'{y:g}'))
        ax.set_ylim(y_min, y_max)

        # State density overlay
        states_list = results[algo].get("_states", [])
        if states_list:
            states_flat = np.concatenate([np.array(s) for s in states_list])
            ax2 = ax.twinx()
            ax2.hist(states_flat, bins=50, density=True, alpha=0.2, color='gray', edgecolor=None, label="Visited States")
            ax2.set_yticks([])
            ax2.set_ylabel("")

            if not handles:
                h1, l1 = ax.get_legend_handles_labels()
                h2, l2 = ax2.get_legend_handles_labels()
                handles = h1 + h2
                labels = l1 + l2
        elif not handles:
            handles, labels = ax.get_legend_handles_labels()

        if i == 0:
            ax.set_ylabel("Consumption Equivalent Variation (CEV)", fontsize=10)

    if handles:
        fig.legend(handles, labels, loc='lower center', ncol=3, bbox_to_anchor=(0.5, 0.02))

    plt.tight_layout(rect=[0, 0.12, 1, 1])
    plt.savefig(out_dir / "4_cev_analysis.pdf", format="pdf")
    plt.close()
    logger.info("Saved: 4_cev_analysis.pdf")


def generate_comparison_table(results: dict, out_dir: Path):
    """Generate LaTeX comparison table from metrics."""
    # Extract summary metrics (not the raw data prefixed with _)
    table_data = {}
    for algo in ALGOS:
        if algo in results and results[algo] is not None:
            # Filter out raw data keys (prefixed with _)
            table_data[algo] = {k: v for k, v in results[algo].items() if not k.startswith("_")}

    if not table_data:
        logger.error("No data available for table generation.")
        return

    table_path = out_dir / "comparison_table.tex"
    generate_latex_table(table_data, ALGOS, table_path)
    logger.info(f"Saved: {table_path}")


# ----------------------------------------------------------------------------
# Main
# ----------------------------------------------------------------------------

def run_comparison():
    """Main entry point for comparison analysis."""
    logger.info(f"Loading results from: {RUNRESULTS_PATH}")

    # Load parameters and compute benchmark
    params = CassKoopmansParams.load_params(TOML_PATH)
    _, grid, policy_bm, _ = compute_benchmark(params)

    # Load metrics for all algorithms
    results = {}
    for algo in ALGOS:
        metrics = load_algo_metrics(algo)
        if metrics is not None:
            # Ensure grid consistency (use the first algo's grid if available)
            if "_grid" in metrics:
                algo_grid = np.array(metrics["_grid"])
                if not np.allclose(grid, algo_grid):
                    logger.warning(f"{algo} has different grid size, using benchmark grid")
            results[algo] = metrics
            logger.info(f"Loaded metrics for {algo}")
        else:
            results[algo] = None

    # Create output directory
    out_dir = RUNRESULTS_PATH / "Comparison"
    out_dir.mkdir(parents=True, exist_ok=True)

    # Generate plots
    plot_learning_curves(results, out_dir)
    plot_policy_functions(results, grid, policy_bm, out_dir)
    plot_euler_errors(results, out_dir)
    plot_cev(results, grid, out_dir)
    
    # Generate LaTeX table
    generate_comparison_table(results, out_dir)

    logger.info(f"Comparison complete. Results in: {out_dir}")


if __name__ == "__main__":
    run_comparison()
